-- -----------------------------------------------------------------------------
-- תעודת זהות של התינוק/ת
--
-- נדרשת בכל ביקור בטיפת חלב, אצל רופא ובקופת חולים, ואף אחד לא זוכר
-- אותה בעל פה בחודשים הראשונים.
--
-- העמודה יושבת על babies ולא על טבלה נפרדת: היא פרט מזהה של התינוק/ת
-- בדיוק כמו תאריך הלידה, וה-RLS שכבר קיים על babies מגן עליה בלי שום
-- מדיניות נוספת — רק חברי המשפחה רואים את השורה.
--
-- תוספתית בלבד: add column if not exists, בלי ברירת מחדל ובלי מגע
-- בנתונים קיימים. הרצה חוזרת בטוחה.
-- -----------------------------------------------------------------------------

alter table babies
  add column if not exists national_id text;

comment on column babies.national_id is
  'תעודת זהות, תשע ספרות כולל ספרת ביקורת. null עד שהיא מונפקת.';
