-- =============================================================================
-- 0013_nursing_segments — מקטעי הנקה
--
-- תוספתי בלבד: מוסיף עמודה אחת לטיימרים הפעילים. לא מוחק, לא משנה
-- ולא נוגע באף רישום קיים.
--
-- למה: עד עכשיו הטיימר שמר רק סכום לכל צד. כשהחלפתם צד, המידע "מתי
-- בדיוק התחילה בשד השני" פשוט לא נשמר בשום מקום. והפסקה של שלוש דקות
-- באמצע נספרה כזמן הנקה.
--
-- עכשיו כל קטע נשמר בנפרד: איזה צד, ממתי, ועד מתי. השהיה היא פשוט
-- סגירת הקטע הנוכחי בלי לפתוח חדש, והמשך פותח קטע חדש באותו צד.
-- =============================================================================

alter table active_timers
  add column if not exists segments jsonb not null default '[]'::jsonb;

comment on column active_timers.segments is
  'מערך של {side, from, to} — to חסר בקטע שרץ כרגע. מקור האמת לזמני ההנקה.';
